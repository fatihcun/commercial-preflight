const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, tr };
let currentLocale: Locale = "en";

export function localeFromSystem(systemLocale: string | undefined): Locale {
  return systemLocale?.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function resolveInitialLocale(storage: LocaleStorage, systemLocale: string | undefined): Locale {
  const persisted = storage.getItem(LOCALE_STORAGE_KEY);
  return persisted === "tr" || persisted === "en" ? persisted : localeFromSystem(systemLocale);
}

export function initializeLocale(storage: LocaleStorage, systemLocale: string | undefined): Locale {
  currentLocale = resolveInitialLocale(storage, systemLocale);
  return currentLocale;
}

export function setLocale(locale: Locale, storage: LocaleStorage): void {
  currentLocale = locale;
  storage.setItem(LOCALE_STORAGE_KEY, locale);
}

export function getLocale(): Locale {
  return currentLocale;
}

export function getLocaleTag(): "en-US" | "tr-TR" {
  return currentLocale === "tr" ? "tr-TR" : "en-US";
}

export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    dictionaries[currentLocale][key],
  );
}

function messageKey(value: string | undefined): MessageKey | null {
  return value && value in en ? value as MessageKey : null;
}

export function applyTranslations(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((node) => {
    const key = messageKey(node.dataset.i18n);
    if (key) node.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((node) => {
    const key = messageKey(node.dataset.i18nAriaLabel);
    if (key) node.setAttribute("aria-label", t(key));
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((node) => {
    const key = messageKey(node.dataset.i18nTitle);
    if (key) node.setAttribute("title", t(key));
  });
  if (root instanceof Document) root.documentElement.lang = currentLocale;
}
